"""Deterministic, collision-safe workspace/container naming and Docker
labels (§50, §51)."""

from __future__ import annotations

import hashlib
import os
import re
from typing import Final, Literal

WorkspaceMode = Literal["persistent", "ephemeral"]

#: Every MCP-managed container carries these (§50). There is no company
#: domain to reverse for a label namespace; the package name is namespace
#: enough and does not pretend to own one.
LABEL_MANAGED: Final = "mcp-chatgpt-sandbox.managed"
LABEL_WORKSPACE_ID: Final = "mcp-chatgpt-sandbox.workspace-id"
LABEL_REPOSITORY_ID: Final = "mcp-chatgpt-sandbox.repository-id"
LABEL_TEST_NAMESPACE: Final = "mcp-chatgpt-sandbox.test-namespace"
TEST_RESOURCE_NAMESPACE_ENV: Final = "MCP_CHATGPT_SANDBOX_TEST_RESOURCE_NAMESPACE"

_SLUG_RUN_RE = re.compile(r"[^a-z0-9]+")


def current_test_resource_namespace() -> str | None:
    """Return a bounded opaque namespace for Docker resources in tests.

    G3R-015 (`docs/GAP3_SPEC.md`): independently started test contexts
    must not share physical Docker resources even when they exercise the
    same logical repository/workspace ids. The raw environment value is
    never copied into Docker names or labels: hashing both bounds the
    metadata and prevents arbitrary test-run text becoming Docker-owned
    identity. Production leaves the variable unset and therefore keeps
    the pre-G3R-015 naming/label contract byte-for-byte.
    """
    raw = os.environ.get(TEST_RESOURCE_NAMESPACE_ENV)
    if not raw:
        return None
    return hashlib.sha256(raw.encode()).hexdigest()[:16]


def container_matches_test_namespace(labels: dict[str, str]) -> bool:
    """Whether `labels` belong to this process's physical test namespace."""
    expected = current_test_resource_namespace()
    actual = labels.get(LABEL_TEST_NAMESPACE)
    return actual == expected if expected is not None else actual is None


def persistent_workspace_id(repository_id: str) -> str:
    """§59 MVP scope: one persistent workspace per repository. Deterministic,
    so reopening a repository always resolves to the same workspace."""
    return f"ws_{repository_id}"


def ephemeral_workspace_id(repository_id: str, *, suffix: str) -> str:
    """Unique per creation: multiple ephemeral workspaces may coexist for
    the same repository (clean-room validation runs, §8.1). `suffix` is
    generated by the caller (`secrets.token_hex`), kept out of this pure
    function so it stays trivially testable."""
    return f"ws_{repository_id}_{suffix}"


def container_name(workspace_id: str) -> str:
    """§51 deterministic naming, physically isolated for test contexts.

    Renaming this prefix does not orphan containers created under the old
    (`mcp-dev-`) scheme, and deliberately so: the generated name is
    persisted on the workspace row at creation, and every lookup that
    could resolve a pre-existing container uses either that stored
    `record.container_name` or a `LABEL_WORKSPACE_ID` filter — never a
    freshly recomputed name. So old and new containers coexist, each
    found by what was recorded for it.

    This is the opposite of `caches.cache_volume_name`, whose docstring
    documents a scheme change as genuinely orphaning; the asymmetry is
    the persistence, not the naming, so do not assume the two behave
    alike. A change here that also made name resolution recompute the
    name would reintroduce exactly that orphaning.
    """
    namespace = current_test_resource_namespace()
    if namespace is None:
        digest = hashlib.sha256(workspace_id.encode()).hexdigest()[:8]
    else:
        digest = hashlib.sha256(f"{workspace_id}\x00{namespace}".encode()).hexdigest()[:8]
    slug = _SLUG_RUN_RE.sub("-", workspace_id.lower()).strip("-")
    if namespace is None:
        return f"mcp-chatgpt-sandbox-{slug}-{digest}"
    return f"mcp-chatgpt-sandbox-{slug}-t{namespace}-{digest}"


def container_labels(*, workspace_id: str, repository_id: str) -> dict[str, str]:
    """§50 ownership labels, including G3R-015 test ownership when active."""
    labels = {
        LABEL_MANAGED: "true",
        LABEL_WORKSPACE_ID: workspace_id,
        LABEL_REPOSITORY_ID: repository_id,
    }
    namespace = current_test_resource_namespace()
    if namespace is not None:
        labels[LABEL_TEST_NAMESPACE] = namespace
    return labels
